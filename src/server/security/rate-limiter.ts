/**
 * Security & Rate Limiting Utility for Public/Mobile Token Endpoints
 *
 * ARCHITECTURAL CONTEXT & LIMITATIONS:
 * 1. Single-Instance / Container Environment:
 *    Maintains an in-memory sliding window of request timestamps per client IP.
 * 2. Multi-Region Serverless Deployment (Vercel / Multi-Node):
 *    Process-local in-memory tracking is isolated to each serverless runtime instance.
 *    In production multi-instance environments, distributed rate limiting should be backed
 *    by an external key-value store (e.g., Upstash Redis / Vercel KV).
 * 3. Brute-Force Safety Invariant:
 *    The primary security guarantee against token guessing is the 256 bits of entropy
 *    generated by `crypto.randomBytes(32)` (2^256 combinations), which makes enumeration
 *    mathematically impossible. Rate limiting provides defense-in-depth against resource
 *    exhaustion and DoS on database queries.
 */

interface RateLimitRecord {
  count: number;
  resetAt: number;
}

const memoryStore = new Map<string, RateLimitRecord>();

// Cleanup stale entries periodically (every 5 minutes)
if (typeof setInterval !== "undefined") {
  const cleanupInterval = setInterval(() => {
    const now = Date.now();
    for (const [key, record] of memoryStore.entries()) {
      if (now > record.resetAt) {
        memoryStore.delete(key);
      }
    }
  }, 5 * 60 * 1000);

  // Unref interval to avoid keeping Node.js process alive in CLI/tests
  if (cleanupInterval.unref) {
    cleanupInterval.unref();
  }
}

export interface RateLimitOptions {
  /** Maximum number of allowed requests within the time window */
  maxRequests: number;
  /** Duration of the time window in milliseconds (default: 60,000ms = 1 min) */
  windowMs?: number;
}

export interface RateLimitResult {
  allowed: boolean;
  remaining: number;
  resetAt: number;
}

/**
 * Checks whether a given identifier (e.g. client IP + action key) is within rate limits.
 */
export function checkRateLimit(
  identifier: string,
  options: RateLimitOptions
): RateLimitResult {
  const now = Date.now();
  const windowMs = options.windowMs || 60 * 1000;
  const maxRequests = options.maxRequests;

  const key = `rl:${identifier}`;
  const record = memoryStore.get(key);

  if (!record || now > record.resetAt) {
    // New or expired window
    memoryStore.set(key, {
      count: 1,
      resetAt: now + windowMs,
    });
    return {
      allowed: true,
      remaining: maxRequests - 1,
      resetAt: now + windowMs,
    };
  }

  if (record.count >= maxRequests) {
    return {
      allowed: false,
      remaining: 0,
      resetAt: record.resetAt,
    };
  }

  record.count += 1;
  return {
    allowed: true,
    remaining: maxRequests - record.count,
    resetAt: record.resetAt,
  };
}

/**
 * Resets rate limit for a specific identifier (useful in test teardown).
 */
export function resetRateLimit(identifier: string): void {
  memoryStore.delete(`rl:${identifier}`);
}

/**
 * Clears the entire rate limit store (for test cleanup).
 */
export function clearRateLimitStore(): void {
  memoryStore.clear();
}
